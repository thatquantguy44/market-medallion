PIPELINE = "finra_short_sale_volume"
CONTRACT = "finra-ssv-postgres-primary/1"
WAREHOUSE_TABLES = {
    "identity": "body",
    "attempts": "attempt_id",
    "captures": "capture_id",
    "versions": "version_id",
    "capture_rows": "capture_id,symbol_raw",
    "partitions": "trade_date,facility_id",
}
CATALOG_TABLES = {
    "identity": "body",
    "generations": "ordinal",
    "snapshot_rows": "generation_id,table_name,row_number",
}


def catalog_sql(statement):
    for name in CATALOG_TABLES:
        statement = re.sub(r"\b" + name + r"\b", "publication_" + name, statement)
    return statement.replace("length(CAST(body AS BLOB))", "octet_length(body)")


ATTEMPT_COLUMNS = (
    "attempt_id,capture_id,run_id,trade_date,facility_id,archived_at,"
    "capture_sequence,started_at,completed_at,status,error_code,profile"
)


class WarehouseConnection(Connection):
    def execute(self, statement, parameters=()):
        statement = re.sub(r"\browid\b", "attempt_ordinal", statement)
        for field in ("body", "profile"):
            statement = statement.replace(
                "length(CAST(" + field + " AS BLOB))", "octet_length(" + field + ")"
            )
        statement = statement.replace(
            "INSERT INTO attempts VALUES", "INSERT INTO attempts (" + ATTEMPT_COLUMNS + ") VALUES"
        )
        return super().execute(statement, parameters)


class CatalogConnection(Connection):
    def execute(self, statement, parameters=()):
        return super().execute(catalog_sql(statement), parameters)


DDL = (
    tuple(s.strip() for s in SCHEMA.split(";") if s.strip() and not s.strip().startswith("PRAGMA"))
    + tuple(
        catalog_sql(s.strip())
        for s in catalog.DDL.split(";")
        if s.strip() and not s.strip().startswith("PRAGMA")
    )
    + (
        "ALTER TABLE attempts ADD COLUMN attempt_ordinal "
        "BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE",
        "CREATE TABLE primary_identity (singleton BOOLEAN PRIMARY KEY CHECK(singleton), "
        "body TEXT NOT NULL, body_sha256 TEXT NOT NULL)",
    )
)
DDL_SHA = hashlib.sha256("\n".join(DDL).encode()).hexdigest()


def fingerprint(db, table, order):
    hasher = hashlib.sha256()
    count = 0
    columns = ATTEMPT_COLUMNS if table == "attempts" else "*"
    for row in db.execute("SELECT " + columns + " FROM " + table + " ORDER BY " + order):
        hasher.update(
            json.dumps(list(row), ensure_ascii=False, separators=(",", ":")).encode() + b"\n"
        )
        count += 1
    return {"count": count, "sha256": hasher.hexdigest()}


def metadata(db):
    rows = db.execute("SELECT body,body_sha256 FROM primary_identity").fetchall()
    if len(rows) != 1:
        raise ValueError("FINRA PostgreSQL identity is missing or ambiguous")
    value = warehouse._document(rows[0][0])
    required = {
        "format",
        "store_id",
        "root_sha256",
        "manifest_sha256",
        "input_kind",
        "ddl_sha256",
        "source_fingerprints",
        "schema_sha256",
    }
    if set(value) != required or not isinstance(value["source_fingerprints"], dict):
        raise ValueError("FINRA PostgreSQL identity fields differ")
    if (
        rows[0][1] != digest(value)
        or value.get("format") != CONTRACT
        or value.get("ddl_sha256") != DDL_SHA
    ):
        raise ValueError("FINRA PostgreSQL identity/DDL contract differs")
    return value


def _validate(db, root, selected, manifest, kind, settings):
    value = metadata(db)
    source = _json(Path(root) / "warehouse.json")
    if (
        value["store_id"] != selected["store_id"]
        or value["store_id"] != source["warehouse_id"]
        or value["root_sha256"] != digest(str(Path(root).resolve()))
        or value["manifest_sha256"] != digest(manifest.to_dict())
        or value["input_kind"] != kind
        or value["schema_sha256"] != schema_fingerprint(db, settings.schema)
    ):
        raise ValueError("FINRA PostgreSQL primary binding/schema mismatch")
    return value


@contextmanager
def connection(root, manifest, kind, *, create, publication=False):
    selected = binding(root, PIPELINE)
    if selected is None:
        raise ValueError("FINRA PostgreSQL primary has not been selected")
    settings = Settings(**selected["postgres"])
    try:
        with pg_connect(settings, read_only=not create) as db:
            _validate(db, root, selected, manifest, kind, settings)
            if publication:
                identity = _json(Path(root) / "parquet.json")
                rows = db.execute("SELECT body FROM publication_identity").fetchall()
                if len(rows) != 1 or catalog.document(rows[0][0]) != identity:
                    raise ValueError("FINRA PostgreSQL publication identity mismatch")
                yield CatalogConnection(db.raw)
            else:
                identity = _json(Path(root) / "warehouse.json")
                rows = db.execute("SELECT body FROM identity").fetchall()
                if len(rows) != 1 or warehouse._document(rows[0][0]) != identity:
                    raise ValueError("FINRA PostgreSQL warehouse identity mismatch")
                yield WarehouseConnection(db.raw)
    except psycopg.Error:
        raise ValueError("FINRA PostgreSQL primary is unavailable or invalid") from None


def _copy(db, source, tables, *, publication=False):
    for name, order in tables.items():
        target = "publication_" + name if publication else name
        if name == "attempts" and not publication:
            columns = ATTEMPT_COLUMNS.split(",") + ["attempt_ordinal"]
            statement = sql.SQL("COPY {} ({}) FROM STDIN").format(
                sql.Identifier(target), sql.SQL(",").join(map(sql.Identifier, columns))
            )
            rows = source.execute("SELECT *,rowid FROM attempts ORDER BY rowid")
        else:
            statement = sql.SQL("COPY {} FROM STDIN").format(sql.Identifier(target))
            rows = source.execute("SELECT * FROM " + name + " ORDER BY " + order)
        with db.raw.cursor().copy(statement) as stream:
            for row in rows:
                stream.write_row(tuple(row))
    if not publication:
        maximum = db.execute("SELECT max(attempt_ordinal) FROM attempts").fetchone()[0]
        db.execute(
            "SELECT setval(pg_get_serial_sequence('attempts','attempt_ordinal'),?,?)",
            (maximum or 1, maximum is not None),
        )


def _verify_copy(db, source, tables, *, publication=False):
    values = {}
    for name, order in tables.items():
        target = "publication_" + name if publication else name
        expected = fingerprint(source, name, order)
        if fingerprint(db, target, order) != expected:
            raise ValueError("FINRA PostgreSQL migration differs from source")
        values[target] = expected
    if not publication:

        def ordered(connection, ordinal):
            hasher = hashlib.sha256()
            count = 0
            for row in connection.execute(
                "SELECT attempt_id," + ordinal + " FROM attempts ORDER BY " + ordinal
            ):
                hasher.update(encoded(list(row)))
                count += 1
            return {"count": count, "sha256": hasher.hexdigest()}

        original = ordered(source, "rowid")
        if ordered(db, "attempt_ordinal") != original:
            raise ValueError("FINRA PostgreSQL attempt order differs from source")
        values["attempt_insertion_order"] = original
    return values


def migrate(root, settings, manifest, *, approved_use, operation, fault=lambda phase: None):
    kind = _admit(manifest, approved_use, operation, {"fixture", "transform"})
    root = Path(root)
    selected = binding(root, PIPELINE)
    if selected is not None:
        if selected["postgres"] != asdict(settings):
            raise ValueError("FINRA PostgreSQL primary target conflicts")
        with connection(root, manifest, kind, create=False):
            return {"status": "ALREADY_PRIMARY", "warehouse": "postgres"}
    shared = dict(approved_use=approved_use, operation=operation)
    with warehouse.ingestion_lock(root), ExitStack() as stack:
        source = stack.enter_context(warehouse.connect(root, manifest, **shared))
        has_catalog = (root / "parquet.json").exists()
        old_catalog = (
            stack.enter_context(catalog.connect(root, manifest, **shared)) if has_catalog else None
        )
        identity = _json(root / "warehouse.json")
        with pg_connect(settings) as db:
            exists = db.execute("SELECT to_regclass('primary_identity')").fetchone()[0]
            if exists:
                value = metadata(db)
                if (
                    value["store_id"] != identity["warehouse_id"]
                    or value["root_sha256"] != digest(str(root.resolve()))
                    or value["schema_sha256"] != schema_fingerprint(db, settings.schema)
                ):
                    raise ValueError("FINRA PostgreSQL namespace belongs to another store")
                values = _verify_copy(db, source, WAREHOUSE_TABLES)
                if old_catalog:
                    values.update(_verify_copy(db, old_catalog, CATALOG_TABLES, publication=True))
                if values != value["source_fingerprints"]:
                    raise ValueError("FINRA PostgreSQL incomplete migration evidence differs")
            else:
                if db.execute(
                    "SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
                    "WHERE n.nspname=? AND c.relkind IN ('r','p','v','m','S')",
                    (settings.schema,),
                ).fetchone():
                    raise ValueError("FINRA PostgreSQL target is not empty")
                db.execute("BEGIN IMMEDIATE")
                try:
                    for statement in DDL:
                        db.execute(statement)
                    _copy(db, source, WAREHOUSE_TABLES)
                    values = _verify_copy(db, source, WAREHOUSE_TABLES)
                    if old_catalog:
                        _copy(db, old_catalog, CATALOG_TABLES, publication=True)
                        values.update(
                            _verify_copy(db, old_catalog, CATALOG_TABLES, publication=True)
                        )
                    value = dict(
                        format=CONTRACT,
                        store_id=identity["warehouse_id"],
                        root_sha256=digest(str(root.resolve())),
                        manifest_sha256=digest(manifest.to_dict()),
                        input_kind=kind,
                        ddl_sha256=DDL_SHA,
                        source_fingerprints=values,
                        schema_sha256=schema_fingerprint(db, settings.schema),
                    )
                    db.execute(
                        "INSERT INTO primary_identity VALUES (TRUE,?,?)",
                        (encoded(value).decode(), digest(value)),
                    )
                    fault("before_commit")
                    db.commit()
                except BaseException:
                    db.rollback()
                    raise
        fault("before_bind")
        bind(root, PIPELINE, settings, identity["warehouse_id"])
    return {"status": "MIGRATED", "warehouse": "postgres", "tables": values}


def initialize_catalog(root, manifest, kind, expected):
    """Initialize native catalog identity/files, recoverably and without SQLite."""
    root = Path(root)
    directory = root / "parquet"
    marker = root / "parquet.json"
    if directory.is_symlink() or marker.is_symlink():
        raise ValueError("FINRA PostgreSQL catalog path is unsafe")
    with connection(root, manifest, kind, create=True) as db:
        saved = db.execute("SELECT body FROM publication_identity").fetchall()
        if len(saved) > 1:
            raise ValueError("FINRA PostgreSQL catalog identity is ambiguous")
        if directory.exists():
            value = _json(directory / "identity.json")
        elif saved:
            value = catalog.document(saved[0][0])
        else:
            from uuid import uuid4

            value = dict(expected, catalog_id=str(uuid4()))
        _identity(value.get("catalog_id"))
        if set(value) != set(expected) | {"catalog_id"} or any(
            value[k] != v for k, v in expected.items()
        ):
            raise ValueError("FINRA PostgreSQL catalog binding differs")
        if saved and catalog.document(saved[0][0]) != value:
            raise ValueError("FINRA PostgreSQL catalog identity differs")
        if not directory.exists():
            if marker.exists():
                raise ValueError("FINRA PostgreSQL catalog files are missing")
            _publish_directory(
                root,
                "parquet",
                {"identity.json": encoded(value), ".staging": None, "snapshots": None},
            )
        if not saved:
            db.execute("BEGIN IMMEDIATE")
            db.execute("INSERT INTO publication_identity VALUES (?)", (encoded(value).decode(),))
            db.commit()
        if not marker.exists():
            _put(marker, encoded(value))
        elif _json(marker) != value:
            raise ValueError("FINRA PostgreSQL catalog marker differs")
