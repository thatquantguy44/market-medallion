"""Source-owned native delayed NAAIM capture/version/latest primary."""

import hashlib
import json
import re
from contextlib import contextmanager
from dataclasses import asdict
from datetime import UTC, date, datetime
from decimal import Decimal
from pathlib import Path
from uuid import uuid4

import psycopg

from market_data_pipeline.shared.files import utc_timestamp, writer_lock
from market_data_pipeline.shared.postgres import (
    Settings,
    bind,
    binding,
    connect,
    schema_fingerprint,
)

PIPELINE = "naaim_exposure_public_delayed"
CONTRACT = "naaim-delayed-postgres-primary/1"
NUMERIC = ("naaim_number", "bearish", "quarter_1", "quarter_2", "quarter_3", "bullish", "deviation")
DDL = (
    "CREATE TABLE retained_captures (capture_id TEXT PRIMARY KEY, receipt_json TEXT, "
    "snapshot_json TEXT, raw_retained BOOLEAN NOT NULL)",
    "CREATE TABLE capture_events (event_id TEXT PRIMARY KEY,capture_id TEXT NOT NULL "
    "REFERENCES retained_captures(capture_id),captured_at TIMESTAMPTZ NOT NULL,"
    "run_id TEXT NOT NULL,body TEXT NOT NULL)",
    "CREATE TABLE versions (ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
    "as_of_date DATE NOT NULL,capture_id TEXT NOT NULL REFERENCES retained_captures(capture_id),"
    "first_seen_at TIMESTAMPTZ NOT NULL,body TEXT NOT NULL,body_sha256 TEXT NOT NULL,"
    + ",".join(n + " NUMERIC NOT NULL" for n in NUMERIC)
    + ")",
    "CREATE INDEX observed_history ON versions(as_of_date,ordinal)",
    "CREATE TABLE latest (singleton BOOLEAN PRIMARY KEY CHECK(singleton),body TEXT NOT NULL)",
    "CREATE TABLE retention_journal (retention_id TEXT PRIMARY KEY,body TEXT NOT NULL)",
    "CREATE TABLE primary_identity (singleton BOOLEAN PRIMARY KEY CHECK(singleton),"
    "body TEXT NOT NULL,body_sha256 TEXT NOT NULL)",
)
DDL_SHA = hashlib.sha256("\n".join(DDL).encode()).hexdigest()


def encoded(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def digest(value):
    return hashlib.sha256(encoded(value).encode()).hexdigest()


def _read(path):
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 64 * 1024 * 1024:
        raise ValueError("NAAIM retained file is unsafe or oversized")
    return json.loads(path.read_text())


def _identity(db, root, selected, settings):
    rows = db.execute("SELECT body,body_sha256 FROM primary_identity").fetchall()
    if len(rows) != 1:
        raise ValueError("NAAIM PostgreSQL identity is missing or ambiguous")
    try:
        value = json.loads(rows[0][0])
        if (
            set(value)
            != {"format", "store_id", "root_sha256", "ddl_sha256", "schema_sha256", "imports"}
            or value["format"] != CONTRACT
            or rows[0][1] != digest(value)
            or value["store_id"] != selected["store_id"]
            or value["root_sha256"] != digest(str(Path(root).resolve()))
            or value["ddl_sha256"] != DDL_SHA
            or value["schema_sha256"] != schema_fingerprint(db, settings.schema)
        ):
            raise ValueError
    except (ValueError, TypeError, KeyError):
        raise ValueError("NAAIM PostgreSQL identity/schema differs") from None
    return value


@contextmanager
def connection(root, *, write=False):
    selected = binding(root, PIPELINE)
    if selected is None:
        raise ValueError("NAAIM PostgreSQL primary is not selected")
    settings = Settings(**selected["postgres"])
    try:
        with connect(settings, read_only=not write) as db:
            if not write:
                db.execute("BEGIN")
            _identity(db, root, selected, settings)
            yield db
    except psycopg.Error:
        raise ValueError("NAAIM PostgreSQL primary is unavailable or invalid") from None


def _projection(version):
    if not isinstance(version, dict) or set(version) != {
        "as_of_date",
        "capture_id",
        "first_seen_at",
        "values",
    }:
        raise ValueError("Invalid retained NAAIM version")
    cap = version["capture_id"]
    if not isinstance(cap, str) or not re.fullmatch("[0-9a-f]{64}", cap):
        raise ValueError("Invalid retained NAAIM capture identity")
    values = version["values"]
    if not isinstance(values, dict) or set(values) != {"as_of_date", *NUMERIC}:
        raise ValueError("Invalid retained NAAIM metric fields")
    observed = date.fromisoformat(version["as_of_date"])
    if values["as_of_date"] != version["as_of_date"]:
        raise ValueError("NAAIM version observation identity differs")
    numbers = [Decimal(values[n]) for n in NUMERIC]
    if any(
        not isinstance(values[n], str) or not amount.is_finite()
        for n, amount in zip(NUMERIC, numbers, strict=True)
    ):
        raise ValueError("NAAIM metric must be exact finite decimal text")
    stamp = datetime.fromisoformat(version["first_seen_at"].replace("Z", "+00:00"))
    utc_timestamp(stamp)
    return observed, cap, stamp, *numbers


def _insert_version(db, version, ordinal):
    observed, cap, stamp, *numbers = _projection(version)
    db.execute(
        "INSERT INTO versions VALUES (?,?,?,?,?,?," + ",".join("?" for _ in NUMERIC) + ")",
        (ordinal, observed, cap, stamp, encoded(version), digest(version), *numbers),
    )


def _versions(db):
    output = []
    for row in db.execute(
        "SELECT as_of_date,capture_id,first_seen_at,body,body_sha256,"
        + ",".join(NUMERIC)
        + " FROM versions ORDER BY ordinal"
    ):
        value = json.loads(row[3])
        observed, cap, stamp, *numbers = _projection(value)
        if digest(value) != row[4] or (observed, cap, stamp, *numbers) != (
            row[0],
            row[1],
            row[2],
            *row[5:],
        ):
            raise ValueError("NAAIM PostgreSQL version integrity differs")
        output.append(value)
    return output


def versions(root):
    with connection(root) as db:
        return _versions(db)


def latest(root):
    with connection(root) as db:
        rows = db.execute("SELECT body FROM latest").fetchall()
        if len(rows) != 1:
            raise ValueError("NAAIM PostgreSQL latest is unavailable")
        value = json.loads(rows[0][0])
        _validate_latest(value)
        return value


def _validate_latest(value):
    from .pipeline import ATTRIBUTION, DELAY_METADATA

    if (
        not isinstance(value, dict)
        or value.get("attribution") != ATTRIBUTION
        or any(value.get(k) != v for k, v in DELAY_METADATA.items())
        or value.get("metric") != "naaim_number"
    ):
        raise ValueError("NAAIM latest attribution/delay identity differs")
    date.fromisoformat(value["as_of_date"])
    if not isinstance(value.get("value"), str) or not Decimal(value["value"]).is_finite():
        raise ValueError("NAAIM latest must preserve finite decimal text")


def _latest(db, value):
    db.execute("DELETE FROM latest")
    if value is not None:
        _validate_latest(value)
        db.execute("INSERT INTO latest VALUES(TRUE,?)", (encoded(value),))


def events(root):
    with connection(root) as db:
        output = []
        for row in db.execute(
            "SELECT event_id,capture_id,captured_at,run_id FROM capture_events ORDER BY event_id"
        ):
            output.append(
                dict(
                    path=Path(root) / row[0],
                    capture_id=row[1],
                    captured_at=row[2].astimezone(UTC),
                    run_id=row[3],
                )
            )
        return output


def snapshot(root, capture_id):
    with connection(root) as db:
        row = db.execute(
            "SELECT snapshot_json FROM retained_captures WHERE capture_id=?", (capture_id,)
        ).fetchone()
        if row is None or row[0] is None:
            raise ValueError("NAAIM retained snapshot is unavailable")
        return json.loads(row[0])


def _capture_record(root, capture_id):
    receipt = Path(root) / "bronze" / capture_id / "receipt.json"
    payload = receipt.with_name("payload.html")
    parsed = Path(root) / "silver" / (capture_id + ".json")
    raw = payload.exists()
    if raw:
        if (
            payload.is_symlink()
            or payload.stat().st_size > 64 * 1024 * 1024
            or hashlib.sha256(payload.read_bytes()).hexdigest() != capture_id
        ):
            raise ValueError("NAAIM retained payload checksum differs")
    r = _read(receipt) if receipt.exists() else None
    s = _read(parsed) if parsed.exists() else None
    if r is not None and (r.get("capture_id") != capture_id or r.get("sha256") != capture_id):
        raise ValueError("NAAIM retained receipt identity differs")
    if s is not None and (
        s.get("capture_id") != capture_id or not isinstance(s.get("observations"), list)
    ):
        raise ValueError("NAAIM retained snapshot identity differs")
    if raw and s is not None:
        from .data.html import parse_table
        from .pipeline import _serialize

        if s["observations"] != [_serialize(o) for o in parse_table(payload.read_bytes())]:
            raise ValueError("NAAIM retained snapshot differs from raw")
    return (
        capture_id,
        encoded(r) if r is not None else None,
        encoded(s) if s is not None else None,
        raw,
    )


def _capture(db, root, capture_id):
    db.execute(
        "INSERT INTO retained_captures VALUES(?,?,?,?) ON CONFLICT(capture_id) DO NOTHING",
        _capture_record(root, capture_id),
    )


def _fingerprints(db):
    captures = [list(r) for r in db.execute("SELECT * FROM retained_captures ORDER BY capture_id")]
    events = []
    for row in db.execute("SELECT * FROM capture_events ORDER BY event_id"):
        events.append([row[0], row[1], utc_timestamp(row[2]), row[3], row[4]])
    return dict(
        versions=digest(_versions(db)),
        latest=digest(json.loads(db.execute("SELECT body FROM latest").fetchone()[0])),
        captures=digest(captures),
        events=digest(events),
    )


def _event(db, root, event, body=None):
    body = _read(event["path"]) if body is None else body
    name = event["path"].relative_to(Path(root)).as_posix()
    db.execute(
        "INSERT INTO capture_events VALUES(?,?,?,?,?)",
        (name, event["capture_id"], event["captured_at"], event["run_id"], encoded(body)),
    )


def publish(root, observations, capture_id, captured_at, run_id, gold, *, fault=lambda phase: None):
    from .pipeline import _append_versions

    with connection(root, write=True) as db:
        with db:
            previous = _versions(db)
            updated = list(previous)
            inserted = _append_versions(updated, observations, capture_id, captured_at)
            _capture(db, root, capture_id)
            fault("after_capture")
            _event(
                db,
                root,
                dict(
                    path=Path(root) / "captures" / (run_id + ".json"),
                    capture_id=capture_id,
                    captured_at=datetime.fromisoformat(captured_at.replace("Z", "+00:00")),
                    run_id=run_id,
                ),
            )
            fault("after_event")
            ordinal = db.execute("SELECT COALESCE(max(ordinal),0) FROM versions").fetchone()[0]
            for i, value in enumerate(updated[len(previous) :], start=ordinal + 1):
                _insert_version(db, value, i)
            fault("after_versions")
            _latest(db, gold)
            fault("before_commit")
    return inserted


def replace_retained(root, retained_versions, active, gold, record, *, fault=lambda phase: None):
    with connection(root, write=True) as db:
        with db:
            bodies = {
                r[0]: json.loads(r[1])
                for r in db.execute("SELECT event_id,body FROM capture_events")
            }
            db.execute("DELETE FROM versions")
            db.execute("DELETE FROM capture_events")
            fault("after_clear")
            for event in active:
                name = event["path"].relative_to(Path(root)).as_posix()
                _event(db, root, event, bodies[name])
            for i, value in enumerate(retained_versions, start=1):
                _insert_version(db, value, i)
            used = {e["capture_id"] for e in active} | {v["capture_id"] for v in retained_versions}
            for row in db.execute("SELECT capture_id FROM retained_captures").fetchall():
                if row[0] not in used:
                    db.execute("DELETE FROM retained_captures WHERE capture_id=?", (row[0],))
            _latest(db, gold)
            db.execute("INSERT INTO retention_journal VALUES(?,?)", (uuid4().hex, encoded(record)))
            fault("before_commit")


def _migrate(root, settings, fault):
    from .operations import _capture_events
    from .pipeline import _versions as legacy_versions
    from .pipeline import read_latest

    if not isinstance(settings, Settings):
        raise ValueError("NAAIM migration requires validated PostgreSQL settings")
    selected = binding(root, PIPELINE)
    if selected:
        if selected["postgres"] != asdict(settings):
            raise ValueError("NAAIM primary target conflicts")
        with connection(root):
            return dict(status="ALREADY_PRIMARY", warehouse="postgres")
    root = Path(root).resolve(strict=True)
    with writer_lock(root):
        values = legacy_versions(root / "silver/versions.json")
        gold = read_latest(root)
        _validate_latest(gold)
        source_events = _capture_events(root)
        ids = {v["capture_id"] for v in values} | {e["capture_id"] for e in source_events}
        captures = [list(_capture_record(root, cap)) for cap in sorted(ids)]
        event_rows = sorted(
            [
                [
                    e["path"].relative_to(root).as_posix(),
                    e["capture_id"],
                    utc_timestamp(e["captured_at"]),
                    e["run_id"],
                    encoded(_read(e["path"])),
                ]
                for e in source_events
            ]
        )
        imports = dict(
            versions=digest(values),
            latest=digest(gold),
            captures=digest(captures),
            events=digest(event_rows),
        )
        from .research_export import _current_versions, _verify_gold

        _verify_gold(root, _current_versions(root))
        with connect(settings) as db:
            if db.execute("SELECT to_regclass('primary_identity')").fetchone()[0]:
                row = db.execute("SELECT body FROM primary_identity").fetchone()
                value = _identity(db, root, dict(store_id=json.loads(row[0])["store_id"]), settings)
                if value["imports"] != imports or _fingerprints(db) != imports:
                    raise ValueError("NAAIM unbound primary differs from retained source")
            else:
                with db:
                    if db.execute(
                        "SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
                        "WHERE n.nspname=current_schema() "
                        "AND c.relkind IN ('r','p','v','m','S')"
                    ).fetchone():
                        raise ValueError("NAAIM PostgreSQL target must be empty")
                    for statement in DDL:
                        db.execute(statement)
                    for cap in sorted(ids):
                        _capture(db, root, cap)
                    for event in source_events:
                        _event(db, root, event)
                    for i, v in enumerate(values, start=1):
                        _insert_version(db, v, i)
                    _latest(db, gold)
                    if _fingerprints(db) != imports:
                        raise ValueError("NAAIM native versions differ from retained source")
                    value = dict(
                        format=CONTRACT,
                        store_id=str(uuid4()),
                        root_sha256=digest(str(root)),
                        ddl_sha256=DDL_SHA,
                        schema_sha256=schema_fingerprint(db, settings.schema),
                        imports=imports,
                    )
                    db.execute(
                        "INSERT INTO primary_identity VALUES(TRUE,?,?)",
                        (encoded(value), digest(value)),
                    )
                    fault("before_commit")
            missing = [
                r[0]
                for r in db.execute(
                    "SELECT capture_id FROM retained_captures WHERE NOT raw_retained"
                )
            ]
        fault("before_bind")
        bind(root, PIPELINE, settings, value["store_id"])
    return dict(
        status="MIGRATED",
        warehouse="postgres",
        versions=len(values),
        captures=len(ids),
        events=len(source_events),
        missing_raw_capture_ids=missing,
    )


def migrate(root, settings, *, fault=lambda phase: None):
    try:
        return _migrate(root, settings, fault)
    except psycopg.Error:
        raise ValueError("NAAIM PostgreSQL migration failed; original files retained") from None
